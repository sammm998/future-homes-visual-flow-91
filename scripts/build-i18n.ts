/**
 * Generates one dictionary module per language (src/utils/i18n/dict.<lang>.ts)
 * from the full translation sources. The browser then downloads only the
 * dictionary for the active language instead of all 13 (~500 kB of JS).
 *
 * Runs automatically before `vite build` (see package.json).
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { translations } from '../src/utils/translationsSource';
import { SEO_META } from '../src/utils/seoMetaTranslations';
import { SEO_META_EXTRA } from '../src/utils/seoMetaExtra';
import { PAGE_META_KEY } from '../src/utils/pageMetaKeys';

/** Page-level SEO title/description for one language, as dictionary keys. */
const pageMetaFor = (lang: string): Record<string, string> => {
  const out: Record<string, string> = {};
  const add = (path: string, meta?: { title: string; description: string }) => {
    if (!meta) return;
    out[PAGE_META_KEY(path, 'title')] = meta.title;
    out[PAGE_META_KEY(path, 'description')] = meta.description;
  };
  for (const [path, byLang] of Object.entries(SEO_META_EXTRA)) add(path, byLang[lang]);
  for (const [path, meta] of Object.entries(SEO_META[lang] ?? {})) add(path, meta);
  return out;
};

const outDir = resolve(import.meta.dirname, '../src/utils/i18n');
mkdirSync(outDir, { recursive: true });

const languages = [...new Set([...Object.keys(translations), ...Object.keys(SEO_META)])].sort();

for (const lang of languages) {
  const dict = { ...(translations[lang] ?? {}), ...pageMetaFor(lang) };
  const body = JSON.stringify(dict, null, 0);
  writeFileSync(
    resolve(outDir, `dict.${lang}.ts`),
    `// AUTO-GENERATED by scripts/build-i18n.ts — do not edit.\n` +
      `// Source of truth: src/utils/translationsSource.ts (+ translations*.ts)\n` +
      `const dict: Record<string, string> = ${body};\nexport default dict;\n`,
  );
}

writeFileSync(
  resolve(outDir, 'index.ts'),
  `// AUTO-GENERATED by scripts/build-i18n.ts — do not edit.\n` +
    `export const loaders: Record<string, () => Promise<{ default: Record<string, string> }>> = {\n` +
    languages.map((l) => `  '${l}': () => import('./dict.${l}'),`).join('\n') +
    `\n};\n`,
);

console.log(`[i18n] generated ${languages.length} dictionaries in src/utils/i18n`);

// Small per-language slice of the new-page copy (page meta + official-source
// labels). Route head() functions and the shared OfficialSources box use it, so
// they no longer pull the full multi-language page copy into every page load.
{
  const { EN } = await import('../src/content/newPagesCopy');
  const all = (await import('../src/content/newPagesCopy.i18n.json')).default as Record<string, typeof EN>;
  const shared: Record<string, { meta: typeof EN.meta; sources: typeof EN.sources }> = {
    en: { meta: EN.meta, sources: EN.sources },
  };
  for (const lang of Object.keys(all).sort()) {
    shared[lang] = { meta: all[lang].meta ?? EN.meta, sources: all[lang].sources ?? EN.sources };
  }
  writeFileSync(
    resolve(import.meta.dirname, '../src/content/newPagesShared.generated.ts'),
    `// AUTO-GENERATED by scripts/build-i18n.ts — do not edit.\n` +
      `// Source of truth: src/content/newPagesCopy.ts + newPagesCopy.i18n.json\n` +
      `export const NEW_PAGES_SHARED = ${JSON.stringify(shared, null, 0)} as const;\n`,
  );
  console.log(`[i18n] generated newPagesShared for ${Object.keys(shared).length} languages`);
}
